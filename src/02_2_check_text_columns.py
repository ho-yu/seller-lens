from pathlib import Path
import pandas as pd


INPUT_PATH = Path("data/raw/reviews.xlsx")


df = pd.read_excel(INPUT_PATH)


# =====================================
# 1. 기본 데이터 수
# =====================================

print("=== 전체 리뷰 수 ===")
print(len(df))


# =====================================
# 2. 제목 / 내용 존재 여부
# =====================================

print("\n=== 리뷰제목 존재 ===")
print(
    df["리뷰제목"].notna().sum()
)


print("\n=== 리뷰내용 존재 ===")
print(
    df["리뷰내용"].notna().sum()
)


# =====================================
# 3. 제목 또는 내용이 하나라도 있는 리뷰
# =====================================

has_text = (
    df["리뷰제목"].notna()
    |
    df["리뷰내용"].notna()
)


print("\n=== 제목 또는 내용이 있는 리뷰 ===")
print(
    has_text.sum()
)


# =====================================
# 4. 리뷰내용은 없지만 제목은 있는 리뷰
# =====================================

title_only = df[
    df["리뷰내용"].isna()
    &
    df["리뷰제목"].notna()
]


print("\n=== 내용은 없지만 제목은 있는 리뷰 ===")
print("개수:", len(title_only))


print(
    title_only[
        [
            "평점",
            "리뷰제목",
            "리뷰내용"
        ]
    ].head(20)
)


# =====================================
# 5. 제목+내용 사용 가능 데이터의 평점 분포
# =====================================

usable_df = df[
    has_text
]


print("\n=== 제목+내용 사용 가능 데이터 평점 분포 ===")

print(
    usable_df["평점"]
    .value_counts()
    .sort_index()
)


# =====================================
# 6. 부정 리뷰 확인
# =====================================

negative_df = usable_df[
    usable_df["평점"] <= 2
]


print("\n=== 사용 가능한 부정 리뷰 ===")
print("개수:", len(negative_df))


print(
    negative_df[
        [
            "평점",
            "리뷰제목",
            "리뷰내용"
        ]
    ]
)