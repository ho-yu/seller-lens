from pathlib import Path
import pandas as pd




# 원본 파일 위치
INPUT_PATH = Path("data/raw/reviews.xlsx")

# 전처리 결과 저장 위치
OUTPUT_PATH = Path("data/processed/reviews.csv")


# ==============================
# 1. Excel 읽기
# ==============================

df = pd.read_excel(INPUT_PATH)


# ==============================
# 2. 필요한 컬럼만 선택
# ==============================

df = df[
    [
        "평점",
        "리뷰내용"
    ]
].copy()


# ==============================
# 3. 리뷰내용이 없는 행 제거
# ==============================

df = df.dropna(
    subset=["리뷰내용"]
)


# ==============================
# 4. 리뷰 앞뒤 공백 제거
# ==============================

df["리뷰내용"] = (
    df["리뷰내용"]
    .astype(str)
    .str.strip()
)


# ==============================
# 5. 중복 리뷰 제거
# ==============================

df = df.drop_duplicates(
    subset=["리뷰내용"]
)


# ==============================
# 6. 3점 제외
# ==============================

df = df[
    df["평점"].isin(
        [1, 2, 4, 5]
    )
]


# ==============================
# 7. label 생성
# ==============================

# 부정 리뷰 = 1
# 긍정 리뷰 = 0

df["label"] = (
    df["평점"] <= 2
).astype(int)


# ==============================
# 8. 결과 확인
# ==============================

print("=== 전처리 후 데이터 수 ===")
print(len(df))


print("\n=== label 분포 ===")
print(
    df["label"]
    .value_counts()
    .sort_index()
)


print("\n=== 상위 5개 ===")
print(
    df.head()
)


# ==============================
# 9. CSV 저장
# ==============================

df.to_csv(
    OUTPUT_PATH,
    index=False,
    encoding="utf-8-sig"
)


print(
    "\n저장 완료:",
    OUTPUT_PATH
)